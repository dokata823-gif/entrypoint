sentences = []
with open("sentences_raw.txt", "r", encoding="utf-8-sig") as f:
    for line in f:
        line = line.strip()
        if not line:
            continue
        m = re.match(r"^(\d+)\.\s*(.*)$", line)
        if m:
            s_id = int(m.group(1))
            full_text = m.group(2).strip()
            pron = ""
            if "[" in full_text and "]" in full_text:
                p_m = re.search(r"\[(.*?)\]", full_text)
                if p_m:
                    pron = p_m.group(1).strip()
                    full_text = full_text[:full_text.find("[")].strip()
            elif "이워저-썸" in full_text:
                pron = "이워저-썸"
                full_text = full_text.replace("이워저-썸", "").strip()
            elif "잍스 츼퍼런" in full_text:
                p_idx = full_text.find("잍스")
                pron = full_text[p_idx:].strip()
                full_text = full_text[:p_idx].strip()
            
            # remove trailing random chars like 뒤, 오, 왼, 충전단자
            for suffix in ["뒤", "오", "왼", "충전단자"]:
                if full_text.endswith(suffix):
                    full_text = full_text[:-len(suffix)].strip()

            ko_text, tag = ko_map.get(s_id, ("한국어 번역 준비 중", "만능 문장"))
            sentences.append({
                "id": s_id,
                "en": full_text,
                "ko": ko_text,
                "tag": tag,
                "pron": pron
            })

print(f"Total parsed: {len(sentences)}")

with open("sentences.json", "w", encoding="utf-8-sig") as f:
    json.dump(sentences, f, ensure_ascii=False, indent=2)
